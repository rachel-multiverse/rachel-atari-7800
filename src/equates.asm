; =============================================================================
; ATARI 7800 EQUATES
; Hardware constants and addresses
; =============================================================================

; -----------------------------------------------------------------------------
; MARIA Registers
; -----------------------------------------------------------------------------
BACKGRND    = $20       ; Background color
PALETTE0    = $21       ; Palette 0 (8 bytes)
PALETTE1    = $21       ; Palette 1 (8 bytes)
MSTAT       = $28       ; MARIA status
CTRL        = $3C       ; MARIA control
DPPH        = $2C       ; Display list pointer high
DPPL        = $30       ; Display list pointer low

; -----------------------------------------------------------------------------
; TIA Registers (for sound)
; -----------------------------------------------------------------------------
AUDC0       = $15
AUDC1       = $16
AUDF0       = $17
AUDF1       = $18
AUDV0       = $19
AUDV1       = $1A

; -----------------------------------------------------------------------------
; RIOT (6532)
; -----------------------------------------------------------------------------
SWCHA       = $280      ; Joystick directions
SWCHB       = $282      ; Console switches
INTIM       = $284      ; Timer value
TIM64T      = $296      ; Set 64-cycle timer

; -----------------------------------------------------------------------------
; Joystick bits (active low)
; -----------------------------------------------------------------------------
JOY_RIGHT   = $80
JOY_LEFT    = $40
JOY_DOWN    = $20
JOY_UP      = $10
JOY_BUTTON_L = $08
JOY_BUTTON_R = $04

; -----------------------------------------------------------------------------
; Game states
; -----------------------------------------------------------------------------
STATE_TITLE   = 0
STATE_CONNECT = 1
STATE_GAME    = 2
STATE_OVER    = 3

; -----------------------------------------------------------------------------
; RUBP Message types
; -----------------------------------------------------------------------------
MSG_HELLO       = $01
MSG_GAME_STATE  = $10
MSG_PLAY_CARD   = $20
MSG_DRAW_CARD   = $21
MSG_PLAYER_WON  = $30

; -----------------------------------------------------------------------------
; Platform ID for Atari 7800
; -----------------------------------------------------------------------------
PLATFORM_ID_LO  = $D7
PLATFORM_ID_HI  = $00

; -----------------------------------------------------------------------------
; Memory map
; -----------------------------------------------------------------------------
RAM_START   = $1800
RAM_END     = $27FF
